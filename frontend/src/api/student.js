import api,{unwrap} from './client'
export const dashboard=async()=>unwrap(await api.get('/student/dashboard'))
export const assessments=async()=>unwrap(await api.get('/student/assessments'))
export const assessmentDetail=async(id)=>unwrap(await api.get(`/student/assessments/${id}`))
export const startAssessment=async(id)=>unwrap(await api.post(`/student/assessments/${id}/start`))
export const getAttempt=async(id)=>unwrap(await api.get(`/student/attempts/${id}`))
export const saveAnswer=async(id,payload)=>unwrap(await api.post(`/student/attempts/${id}/answers`,payload))
export const submitAttempt=async(id)=>unwrap(await api.post(`/student/attempts/${id}/submit`))
export const results=async()=>unwrap(await api.get('/student/results'))
export const result=async(id)=>unwrap(await api.get(`/student/results/${id}`))
export const profile=async()=>unwrap(await api.get('/auth/me'))
export const updateProfile=async(payload)=>unwrap(await api.put('/auth/me',payload))
